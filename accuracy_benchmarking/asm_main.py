"""
Python CLI entry point for the ASM implementation (challenge mode, WORKQUEUE W4).

Usage:
  python asm_main.py <input_file> [budget]
  python asm_main.py --no-asm <input_file>   # CONTROL: serve all, no ASM
  python asm_main.py                          # embedded toy sample (same as benchmark.py)

Input file line format (generated by challenge-documents/mk_fixture.py):
  line 1 = question (single line, "\\t"/"\\n" escapes)
  line 2 = default budget (integer words)
  lines 3..N = <address>\t<text>

Input parsing happens outside the timed section; the algorithm and JSON
serialization stay inside it, exactly like the C/Rust/Go implementations.

The --no-asm control is the paired comparator required by WORKQUEUE §R19:
it serves the ENTIRE input as context in file order — no ranking, no
selection, no score>0 retrieval filter — and times only the load->serve
assembly. Every metric category is measured against this control and
against an ASM pass per source-code build.
"""

import json
import re
import sys
import time
from asm import ASM, Fragment

WORD_RE = re.compile(r"[A-Za-z0-9]+")

TOY_QUESTION = "How does ASM retrieve relevant context and keep the context bounded?"
TOY_BUDGET = 28
TOY_FRAGMENTS = [
    Fragment("architecture", "ASM uses deterministic retrieval and bounded context assembly."),
    Fragment("memory", "Persistent memory should preserve important project state across sessions."),
    Fragment("retrieval", "Retrieval ranks relevant fragments using question term overlap."),
    Fragment("voice", "Voice output should remain responsive and interruptible."),
    Fragment("safety", "Snapshots validation and rollback protect autonomous project changes."),
    Fragment("research", "Research agents can investigate new techniques and report evidence."),
]


def unescape(text):
    """Left-to-right scanner: \\t -> TAB, \\n -> NL, \\\\ -> backslash."""
    out = []
    i = 0
    while i < len(text):
        if text[i] == "\\" and i + 1 < len(text):
            nxt = text[i + 1]
            if nxt == "t":
                out.append("\t")
                i += 2
                continue
            if nxt == "n":
                out.append("\n")
                i += 2
                continue
            if nxt == "\\":
                out.append("\\")
                i += 2
                continue
        out.append(text[i])
        i += 1
    return "".join(out)


def run_file(path, budget_arg):
    with open(path, "r", encoding="utf-8", newline="") as handle:
        lines = handle.read().split("\n")

    question = unescape(lines[0].rstrip("\r"))
    default_budget = int(lines[1].strip()) if len(lines) > 1 and lines[1].strip() else 0
    if budget_arg is not None:
        budget = int(budget_arg)
    else:
        budget = default_budget

    fragments = []
    for line in lines[2:]:
        line = line.rstrip("\r")
        if not line or "\t" not in line:
            continue
        address, text = line.split("\t", 1)
        fragments.append(Fragment(address, text))

    result = ASM().run(question, fragments, budget)

    start = time.perf_counter_ns()
    payload = json.dumps(result)
    internal = time.perf_counter_ns() - start

    print(payload)
    sys.stderr.write(f"BENCHMARK_NS {internal}\n")


def run_toy():
    start = time.perf_counter_ns()
    payload = json.dumps(ASM().run(TOY_QUESTION, list(TOY_FRAGMENTS), TOY_BUDGET))
    internal = time.perf_counter_ns() - start
    sys.stderr.write(f"BENCHMARK_NS {internal}\n")


def run_control(path):
    """No-ASM control pass (WORKQUEUE §R19 paired-measurement rule): serve
    every input unit verbatim in file order - no query, no ranking, no
    selection, no score>0 retrieval filter. Timed section = serve assembly
    + word count + JSON serialization, mirroring the ASM path."""
    with open(path, "r", encoding="utf-8", newline="") as handle:
        lines = handle.read().split("\n")

    question = unescape(lines[0].rstrip("\r"))
    fragments = []
    for line in lines[2:]:
        line = line.rstrip("\r")
        if not line or "\t" not in line:
            continue
        address, text = line.split("\t", 1)
        fragments.append(Fragment(address, text))

    start = time.perf_counter_ns()
    context_parts = []
    selected = []
    original_words = 0
    for fragment in fragments:
        token_count = len(WORD_RE.findall(fragment.text))
        original_words += token_count
        context_parts.append(fragment.text)
        selected.append({"address": fragment.address, "score": 1})
    result = {
        "mode": "no-asm control",
        "question_words": len(WORD_RE.findall(question)),
        "original_source_words": original_words,
        "retrieved_addresses": [f.address for f in fragments],
        "selected": selected,
        "context": " ".join(context_parts),
        "context_words": original_words,
    }
    payload = json.dumps(result)
    internal = time.perf_counter_ns() - start

    print(payload)
    sys.stderr.write(f"BENCHMARK_NS {internal}\n")


def main():
    args = [a for a in sys.argv[1:] if a != "--no-asm"]
    control = "--no-asm" in sys.argv[1:]
    if args:
        if control:
            run_control(args[0])
        else:
            run_file(args[0], args[1] if len(args) > 1 else None)
    else:
        run_toy()


if __name__ == "__main__":
    main()
