"""
Challenge runner (WORKQUEUE W5): runs the four ASM implementations over the
NOAA challenge fixture at a range of small context-word budgets, asserts
cross-implementation MATCH per budget, and writes:

  results/challenge_results.json      canonical per-budget results + timing
  results/prompt_budget_<B>.txt       ready-to-use prompt (question + bounded
                                      context) for testing any local model
                                      against the challenge criteria
  results/criteria_checklist.md       the five challenge criteria verbatim
                                      from challenge-documents/challenge.txt,
                                      for scoring local-model responses

The runner never answers the challenge and never runs an LLM; context
windows are counted in whitespace-delimited words, never "tokens".

Usage:
  python challenge.py [--budgets 150,300,600,1200,2400] [--input asm_input.txt]
                      [--build]
"""

import argparse
import hashlib
import json
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

from benchmark import build, find_go_command  # noqa: E402  (runner reuse)

DEFAULT_BUDGETS = [150, 300, 600, 1200, 2400]
RESULTS_DIR = ROOT / "results"


def impl_commands(input_path, budget):
    common = [str(input_path), str(budget)]
    return {
        "Python": [sys.executable, "asm_main.py"] + common,
        "C": [str(ROOT / ("asm_c.exe" if sys.platform == "win32" else "asm_c"))] + common,
        "Rust": [str(ROOT / ("asm_rust.exe" if sys.platform == "win32" else "asm_rust"))] + common,
        "Go": [str(ROOT / ("asm_go.exe" if sys.platform == "win32" else "asm_go"))] + common,
    }


def run_one(name, command):
    start = time.perf_counter_ns()
    proc = subprocess.run(command, cwd=ROOT, capture_output=True, text=True)
    elapsed = time.perf_counter_ns() - start
    if proc.returncode != 0:
        return None, None, elapsed, proc.stderr.strip() or proc.stdout.strip()

    internal = None
    for line in proc.stderr.splitlines():
        if line.startswith("BENCHMARK_NS "):
            internal = int(line.split()[1])
    try:
        return json.loads(proc.stdout), internal, elapsed, None
    except json.JSONDecodeError:
        return None, internal, elapsed, "invalid JSON on stdout"


def write_prompt_file(budget, result, source_words):
    context = result["context"]
    path = RESULTS_DIR / f"prompt_budget_{budget}.txt"
    path.write_text(
        "\n".join(
            [
                f"# ASM challenge prompt - budget {budget} context words",
                "",
                "Generated by challenge.py. The bounded context below was assembled",
                "deterministically by the ASM retriever from the NOAA challenge",
                "fixture. Score any answer with results/criteria_checklist.md.",
                "",
                "## Question",
                "",
                prompt_question(),
                "",
                "## Rule for the responder",
                "",
                "Use ONLY the context excerpt below as the source of facts.",
                "",
                f"## Context ({result['context_words']} words of {source_words} source words)",
                "",
                context,
                "",
            ]
        ),
        encoding="utf-8",
    )
    return path


_PROMPT_QUESTION = None


def prompt_question():
    global _PROMPT_QUESTION
    if _PROMPT_QUESTION is None:
        line = (ROOT / "challenge-documents" / "challenge.txt").read_text(
            encoding="utf-8"
        ).splitlines()[0]
        _PROMPT_QUESTION = line.removeprefix("#question:").strip()
    return _PROMPT_QUESTION


def write_criteria_checklist():
    challenge_text = (ROOT / "challenge-documents" / "challenge.txt").read_text(
        encoding="utf-8"
    )
    criteria_block = challenge_text.split("Criterion:", 1)[-1].strip()
    checklist = "\n".join(
        [
            "# Challenge criteria checklist (for scoring local-model responses)",
            "",
            "Score a model's answer using ONLY its response and, where the",
            "criteria reference the document, the bounded context served to it.",
            "These criteria are quoted verbatim from",
            "challenge-documents/challenge.txt (oracle; do not modify).",
            "",
            "Usage: for each prompt_budget_<B>.txt run against a local model,",
            "apply each criterion row to that model's response.",
            "",
            "## Criteria (positive form, then failing form)",
            "",
            criteria_block,
            "",
        ]
    )
    path = RESULTS_DIR / "criteria_checklist.md"
    path.write_text(checklist, encoding="utf-8")
    return path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--budgets",
        default=",".join(str(b) for b in DEFAULT_BUDGETS),
        help="comma-separated context-word budgets",
    )
    parser.add_argument(
        "--input", default="asm_input.txt", help="fixture input file (line format)"
    )
    parser.add_argument("--build", action="store_true", help="rebuild binaries first")
    args = parser.parse_args()

    input_path = ROOT / args.input
    if not input_path.exists():
        raise SystemExit(
            f"missing {input_path}; run: python challenge-documents/mk_fixture.py"
        )

    budgets = [int(b) for b in args.budgets.split(",") if b.strip()]
    if args.build:
        build()

    RESULTS_DIR.mkdir(exist_ok=True)
    fixture_sha = hashlib.sha256(input_path.read_bytes()).hexdigest()

    per_budget = {}
    for budget in budgets:
        results = {}
        for name, command in impl_commands(input_path, budget).items():
            result, internal, elapsed, error = run_one(name, command)
            if error is not None:
                print(f"BUDGET {budget}: {name} FAILED: {error}")
                raise SystemExit(1)
            results[name] = {
                "result": result,
                "process_ns": elapsed,
                "internal_ns": internal if internal is not None else elapsed,
            }

        # Cross-implementation MATCH: full canonical comparison.
        baseline_name = "Python"
        baseline = results[baseline_name]["result"]
        mismatch = None
        for name, entry in results.items():
            if entry["result"] != baseline:
                differing = sorted(
                    key
                    for key in set(baseline) | set(entry["result"])
                    if entry["result"].get(key) != baseline.get(key)
                )
                mismatch = (name, differing)
                break
        if mismatch:
            print(
                f"BUDGET {budget}: CROSS-IMPL MISMATCH "
                f"({mismatch[0]} differs in {mismatch[1]})"
            )
            raise SystemExit(1)

        summary = {
            impl: {
                "context_words": entry["result"]["context_words"],
                "retrieved": len(entry["result"]["retrieved_addresses"]),
                "selected": len(entry["result"]["selected"]),
                "internal_ns": entry["internal_ns"],
                "process_ns": entry["process_ns"],
            }
            for impl, entry in results.items()
        }
        context = baseline["context"]
        summary["context_sha256"] = hashlib.sha256(
            json.dumps(context, ensure_ascii=True).encode("utf-8")
        ).hexdigest()
        summary["all_match"] = True
        summary["selected"] = baseline["selected"]
        summary["retrieved_addresses"] = baseline["retrieved_addresses"]
        per_budget[str(budget)] = summary

        write_prompt_file(budget, baseline, baseline["original_source_words"])

        print(
            f"budget {budget:>5}: context_words={baseline['context_words']:>5} "
            f"selected={len(baseline['selected']):>3}/{len(baseline['retrieved_addresses'])} "
            f"retrieved  |  cross-impl MATCH x4"
        )

    payload = {
        "fixture": input_path.name,
        "fixture_sha256": fixture_sha,
        "word_unit": "words (whitespace-delimited [A-Za-z0-9]+ runs)",
        "budgets": budgets,
        "per_budget": per_budget,
    }
    out_path = RESULTS_DIR / "challenge_results.json"
    out_path.write_text(json.dumps(payload, indent=1) + "\n", encoding="utf-8")
    checklist_path = write_criteria_checklist()

    print(f"\nwrote {out_path}")
    print(f"wrote {RESULTS_DIR / 'prompt_budget_*.txt'} (local-model prompts)")
    print(f"wrote {checklist_path}")


if __name__ == "__main__":
    main()
